    public function index(Request $request)
    {
        if (!$this->isSelectedCompany()) {
            return redirect()->route('home.select');
        }
        $company = CurrentUser::currentCompany();
        $companyId = $company->id;
        $certificate = Certificate::where('company_id', $companyId)
            ->where('delete_flg', 0)
            ->first();
        if($certificate !== null) {
            $certificate = true;
        } else {
            $certificate = false;
        }

        $japanEra = '令和';
        $year = date("Y");
        $japanEraYear = $year - 2018;
        $month = ltrim(date("m"), '0');
        $day = ltrim(date("d"), '0');
        $todaySet = array(
            "japanEra" => $japanEra,
            "japanEraYear" => $japanEraYear,
            "year" => $year,
            "month" => $month,
            "day" => $day
        );
        return view('ledger.wage_certificates_employment_insured_at_sixty', ['company' => $company, 'todaySet' => $todaySet, 'certificate' => $certificate]);
    }

